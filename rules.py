@dataclass
class Finding:
    article: str
    title: str
    reason: str
    penalty: str = TODO


@dataclass
class Verdict:
    criminal: bool
    findings: list = field(default_factory=list)
    qualifiers: list = field(default_factory=list)
    evidence: list = field(default_factory=list)
    note: str = ""


def qualify(selected: set) -> Verdict:
    """selected - множество ключей отмеченных признаков."""
    f = {key: (key in selected) for key, _ in FLAGS}

    # 1. Без умысла в рассматриваемых составах ответственности нет
    if not f["intent"]:
        return Verdict(
            criminal=False,
            note=("Умысел не установлен. Составы, рассматриваемые системой, предполагают "
                  "умышленную форму вины. Возможна административная, гражданско-правовая "
                  "или дисциплинарная ответственность."))

    # 2. Применяем правила
    findings = [Finding(code, ARTICLES[code]["title"], why)
                for code, cond, why in RULES if cond(f)]

    if not findings:
        return Verdict(
            criminal=False,
            note=("Признаков уголовно наказуемого деяния по рассматриваемым составам "
                  "недостаточно. Возможно гражданско-правовое или дисциплинарное нарушение."))

    # 3. Квалифицирующие признаки
    qualifiers = [text for key, text in QUALIFIERS.items() if f[key]]

    # 4. Рекомендации по доказательствам (без повторов, порядок сохраняется)
    evidence = []
    for fd in findings:
        for item in ARTICLES[fd.article]["evidence"]:
            if item not in evidence:
                evidence.append(item)
    evidence += GENERAL_EVIDENCE

    return Verdict(True, findings, qualifiers, evidence)


