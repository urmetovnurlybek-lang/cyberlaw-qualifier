def format_verdict(v: Verdict) -> str:
    """Вердиктің мәтіндік көрінісі (GUI және есеп үшін)."""
    if not v.criminal:
        return "НӘТИЖЕ: қылмыстық жазаланатын белгілер анықталмады.\n\n" + v.note

    lines = ["ҚҰҚЫҚТЫҚ ҚОРЫТЫНДЫ", "=" * 50, ""]
    for i, fd in enumerate(v.findings, 1):
        lines += [f"{i}. ҚР ҚК {fd.article}-бабы - {fd.title}",
                  f"   Негіздеме: {fd.reason}",
                  f"   Жаза: {fd.penalty}", ""]
    if v.qualifiers:
        lines += ["Квалификациялаушы белгілер:"] + [f"  • {q}" for q in v.qualifiers] + [""]
    lines += ["Дәлелдемелерді алғашқы жинау бойынша ұсыныстар:"]
    lines += [f"  {i}. {e}" for i, e in enumerate(v.evidence, 1)]
    lines += ["", "Назар аударыңыз: қорытынды оқу сипатында және заңгердің кеңесін алмастырмайды."]
    return "\n".join(lines)
