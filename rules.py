def format_verdict(v: Verdict) -> str:
    """Текстовое представление вердикта (для GUI и для отчёта)."""
    if not v.criminal:
        return "РЕЗУЛЬТАТ: уголовно наказуемых признаков не выявлено.\n\n" + v.note

    lines = ["ЮРИДИЧЕСКОЕ ЗАКЛЮЧЕНИЕ", "=" * 50, ""]
    for i, fd in enumerate(v.findings, 1):
        lines += [f"{i}. Ст. {fd.article} УК РК - {fd.title}",
                  f"   Основание: {fd.reason}",
                  f"   Наказание: {fd.penalty}", ""]
    if v.qualifiers:
        lines += ["Квалифицирующие признаки:"] + [f"  • {q}" for q in v.qualifiers] + [""]
    lines += ["Рекомендации по первичному сбору доказательств:"]
    lines += [f"  {i}. {e}" for i, e in enumerate(v.evidence, 1)]
    lines += ["", "Внимание: заключение носит учебный характер и не заменяет консультацию юриста."]
    return "\n".join(lines)
