@dataclass
class Finding:
    article: str
    title: str
    reason: str
    penalty: str = ""


@dataclass
class Verdict:
    criminal: bool
    findings: list = field(default_factory=list)
    qualifiers: list = field(default_factory=list)
    evidence: list = field(default_factory=list)
    note: str = ""


def qualify(selected: set) -> Verdict:
    """selected - белгіленген белгілер кілттерінің жиыны."""
    f = {key: (key in selected) for key, _ in FLAGS}

    # 1. Қасақаналық болмаса - жауапкершілік жоқ
    if not f["intent"]:
        return Verdict(
            criminal=False,
            note=("Қасақаналық анықталмаған. Жүйе қарастыратын құрамдар "
                  "қасақана кінә нысанын болжайды. Әкімшілік, азаматтық-құқықтық "
                  "немесе тәртіптік жауапкершілік болуы мүмкін."))

    # 2. Ережелерді қолдану
    findings = []
    for code, cond, why in RULES:
        if cond(f):
            art = ARTICLES[code]
            findings.append(Finding(code, art["title"], why, art.get("penalty", "")))

    if not findings:
        return Verdict(
            criminal=False,
            note=("Қарастырылатын құрамдар бойынша қылмыстық жазаланатын әрекет "
                  "белгілері жеткіліксіз. Азаматтық-құқықтық немесе тәртіптік "
                  "құқықбұзушылық болуы мүмкін."))

    # 3. Квалификациялаушы белгілер
    qualifiers = [text for key, text in QUALIFIERS.items() if f[key]]

    # 4. Дәлелдеме жинау бойынша ұсыныстар
    evidence = []
    for fd in findings:
        for item in ARTICLES[fd.article]["evidence"]:
            if item not in evidence:
                evidence.append(item)
    evidence += GENERAL_EVIDENCE

    return Verdict(True, findings, qualifiers, evidence)


